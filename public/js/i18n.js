let current = 'es';

export function setLang(id) {
  current = T[id] ? id : 'es';
  document.documentElement.lang = current === 'va' ? 'ca' : current;
}

export function getLang() {
  return LANGS.find((l) => l.id === current);
}

export function t(key, vars) {
  let s = T[current][key] ?? T.es[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

export function listJoin(items) {
  if (items.length <= 1) return items.join('');
  return `${items.slice(0, -1).join(', ')} ${t('sum.and')} ${items[items.length - 1]}`;
}

export function fmtDate(date, opts) {
  try {
    return new Intl.DateTimeFormat(getLang().locale, opts).format(date);
  } catch {
    return new Intl.DateTimeFormat('es-ES', opts).format(date);
  }
}
